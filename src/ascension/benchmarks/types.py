"""Value-object DTOs for the benchmarks module.

Frozen slots dataclasses, same pattern as `src/ascension/sandbox/types.py`
and `src/ascension/llm/types.py`. Pydantic is reserved for Agora nodes
(Phase 5.0, sibling lane) — these shapes are internal-only transport
records for Phase 7.0+ callers.

Plain English: these are the two "packing boxes" this phase produces.
``BenchmarkSpec`` is the problem you want simulated (which toy system,
how many runs, how much noise, which random seed). ``TrajectoryBundle``
is the result (the clean simulated data, the noisy version, and a hidden
20% we'll use later to grade predictions).

Invariants (documented here so a grep regression test can confirm
presence — see `tests/benchmarks/test_types.py`):
  - ``noise_sigma`` on `BenchmarkSpec` is a fraction of per-trajectory RMS
    (PySINDy convention, not absolute units) — RESEARCH Pitfall #7.
  - ``train_mask`` on `TrajectoryBundle` is a bool array of shape
    (n_trajectories,), with ~80% True (Plan-01 rounds 0.8 * N).

Binding decisions:
  - 06.0 RESEARCH §Pattern 1 lines 257–276: canonical field list for both
    dataclasses.
  - 06.0 PATTERNS §Shared Pattern C: frozen slots dataclass, not Pydantic.
  - 06.0 PATTERNS §Shared Pattern I: invariant documented in source for
    grep-regression test (noise_sigma convention).

Pitfalls honored:
  - RESEARCH #7 (noise convention) — docstring below spells out the
    "fraction of per-trajectory RMS" phrasing verbatim.

Threat-model mitigations: N/A — pure-compute phase, no network/auth/secret
surface per RESEARCH §Security Domain lines 690–702.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np

SystemName = Literal["lotka_volterra", "van_der_pol", "lorenz"]


@dataclass(frozen=True, slots=True)
class BenchmarkSpec:
    """Immutable problem specification for one ODE benchmark run.

    Plain English: this is the "recipe card" for a benchmark. It says
    which toy physics system to simulate, how many slightly-different
    starting conditions to try, how much noise to add, how long the
    simulated run is, and which random seed locks every coin flip so
    two people running the same spec get bit-identical trajectories.

    Attributes:
      system: Which ODE to simulate. One of
        ``"lotka_volterra"`` (predator-prey), ``"van_der_pol"``
        (self-sustaining oscillator), ``"lorenz"`` (chaotic butterfly).
      n_trajectories: How many independent runs from slightly-different
        initial conditions (ICs). Each run becomes one row in
        ``TrajectoryBundle.clean`` and ``.noisy``.
      noise_sigma: Standard deviation of the Gaussian measurement noise,
        expressed as a fraction of per-trajectory RMS magnitude
        (PySINDy convention). 0.01 means "1% noise relative to how big
        the trajectory values themselves are". This keeps the meaning
        of "1% noise" the same across systems whose values range wildly
        (Lorenz ~[-20,20] vs VdP ~[-2,2]). Ref: RESEARCH Pitfall #7
        (noise_sigma is fraction of per-trajectory RMS).
      n_samples: How many points in time we record along one simulated
        run (like frames in a flipbook).
      seed: Integer fed into ``np.random.default_rng(seed)`` that seeds
        both the IC perturbation draw and the noise draw. Same seed →
        bit-identical output.
      ic_spread: Optional multiplier on the Gaussian perturbation radius
        around the system's default initial condition. Default is ``None``
        (sentinel) — when None, ode.py looks up the per-system value from
        DEFAULT_PARAMS (LV=0.03, VdP=1.0, Lorenz=1.0 per Phase 6.1 D-04
        amended). When a caller passes an explicit float (including
        ``1.0``), THAT value wins — the registry is NOT consulted. This
        is the D-04 "caller wins for real" semantics (plan-check
        BLOCKER-2 resolution). Old default was ``1.0``; the sentinel fix
        eliminates the silent-override failure mode where a caller who
        legitimately typed ``ic_spread=1.0`` could not be distinguished
        from a caller who simply didn't pass the kwarg.
      t_span_override: Optional ``(t_start, t_end)`` override. ``None``
        uses the registry default per system.
    """

    system: SystemName
    n_trajectories: int
    noise_sigma: float
    n_samples: int
    seed: int
    ic_spread: float | None = None
    t_span_override: tuple[float, float] | None = None


@dataclass(frozen=True, slots=True)
class TrajectoryBundle:
    """Output of ``generate_trajectories()``.

    Plain English: this is the "packing box" generated by one benchmark
    run. It contains the time axis, the clean simulated values, the
    noisy measurement version, the starting conditions we picked, and
    an 80/20 train/held-out split so scoring later can check predictions
    against data the agent never saw. ``library_versions`` pins the exact
    scipy/sympy/pysindy/numpy versions active at generation time so
    six months from now we can re-run the same spec and get bit-identical
    numbers (SCOPE §22.2 reproducibility).

    Attributes:
      spec: The `BenchmarkSpec` used to generate this bundle. Stored so
        a bundle is self-describing.
      t: Time axis, shape ``(n_samples,)``. All trajectories share this
        axis.
      clean: Noise-free simulated trajectories, shape
        ``(n_trajectories, n_samples, dim)``. ``dim`` is 2 for LV/VdP
        and 3 for Lorenz.
      noisy: ``clean`` plus Gaussian measurement noise scaled to
        ``spec.noise_sigma`` × per-trajectory RMS, same shape as
        ``clean``. When ``spec.noise_sigma == 0.0``, ``noisy`` equals
        ``clean`` exactly (element-wise).
      ics: The initial conditions actually used, shape
        ``(n_trajectories, dim)``. Row i is the starting point of
        ``clean[i]`` / ``noisy[i]``.
      train_mask: Bool mask of shape ``(n_trajectories,)``. Roughly 80%
        True. Downstream scoring uses ``~train_mask`` for held-out
        evaluation. Split is deterministic per seed.
      library_versions: Dict with exactly four keys —
        ``"scipy"``, ``"sympy"``, ``"pysindy"``, ``"numpy"`` — mapping
        to the versions active during generation. Consumed by the
        `spec.json` artifact in Plan 03's `io.py` for reproducibility
        audit (SCOPE §22.2).
    """

    spec: BenchmarkSpec
    t: np.ndarray
    clean: np.ndarray
    noisy: np.ndarray
    ics: np.ndarray
    train_mask: np.ndarray
    library_versions: dict[str, str]
